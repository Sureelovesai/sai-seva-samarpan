function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const wb = new ExcelJS.Workbook();
  wb.creator = "QA matrix generator";
  wb.created = new Date();

  const ws = wb.addWorksheet("Home page", {
    views: [{ state: "frozen", ySplit: 1 }],
  });
  ws.addRow(HEADERS);
  const headerRow = ws.getRow(1);
  headerRow.font = { bold: true };
  headerRow.fill = {
    type: "pattern",
    pattern: "solid",
    fgColor: { argb: "FFE8E0D8" },
  };

  for (const r of ROWS) {
    ws.addRow(r);
  }

  ws.columns = [
    { width: 10 },
    { width: 12 },
    { width: 22 },
    { width: 36 },
    { width: 28 },
    { width: 28 },
    { width: 36 },
    { width: 36 },
    { width: 40 },
    { width: 40 },
    { width: 40 },
    { width: 28 },
    { width: 8 },
  ];

  ws.autoFilter = {
    from: { row: 1, column: 1 },
    to: { row: 1, column: HEADERS.length },
  };

  const legend = wb.addWorksheet("Roles on header");
  legend.addRow(["Role / actor", "Expected 2nd row in SiteHeader (home is same as other pages)"]);
  legend.getRow(1).font = { bold: true };
  const legendRows = [
    ["Guest", "No second row"],
    ["Logged-in (no special roles)", "No second row"],
    ["eventAdminOnly", "Event Admin Dashboard only"],
    ["SEVA_COORDINATOR (not ADMIN)", "Seva Admin Dashboard; no Roles"],
    ["BLOG_ADMIN (not ADMIN)", "Seva Admin Dashboard; no Roles"],
    ["REGIONAL_SEVA_COORDINATOR / NATIONAL_SEVA_COORDINATOR", "Seva Admin Dashboard; no Roles unless ADMIN"],
    ["ADMIN", "Seva Admin Dashboard + Roles"],
  ];
  for (const lr of legendRows) legend.addRow(lr);
  legend.columns = [{ width: 42 }, { width: 50 }];

  return wb.xlsx.writeFile(OUT_FILE);
}

main().then(() => {
  console.log("Wrote", OUT_FILE);
});
